def test_full_report_is_byte_reproducible_and_binds_input(tmp_path: Path) -> None:
    path = tmp_path / "small.jsonl"
    path.write_text(json.dumps(_record()) + "\n", encoding="utf-8")
    first = check_census(path, denser_order=8)
    second = check_census(path, denser_order=8)
    assert json.dumps(first, sort_keys=True, allow_nan=False) == json.dumps(
        second, sort_keys=True, allow_nan=False
    )
    assert first["input_sha256"] == hashlib.sha256(path.read_bytes()).hexdigest()
    assert first["strictest_trajectory_count"] == 1
    assert first["status"] == "passed_numerical_core_checks"
    assert first["unavailable_representative_cutoffs"] == ["1000", "1000000"]
    assert first["certification_status"] == "not_certified"
    root = Path(__file__).parents[1]
    assert (
        first["imported_grid_source_sha256"]
        == hashlib.sha256((root / "kernelgecp/grids.py").read_bytes()).hexdigest()
    )
    assert (
        first["environment"]["uv_lock_sha256"]
        == hashlib.sha256((root / "uv.lock").read_bytes()).hexdigest()
    )
    assert first["environment"]["mpmath_backend"] == str(mp.libmp.BACKEND)


def test_compatible_prefixes_select_strictest_case() -> None:
    loose = _record(1)
    loose["tolerance"] = "0.9"
    strict = _record(2)
    assert strictest_records([loose, strict]) == [strict]
    wrong = copy.deepcopy(loose)
    wrong["residual_history"][0] = "0.9"
    with pytest.raises(ValueError, match="incompatible prefix"):
        strictest_records([wrong, strict])
    with pytest.raises(ValueError, match="duplicate cutoff/tolerance"):
        strictest_records([strict, copy.deepcopy(strict)])


