def _record(rank: int = 2) -> dict:
    """Analytically specified small cores, not generated by the census runner."""
    with mp.workprec(160):
        a = 1 / (1 + mp.e)
        b = mp.e / (1 + mp.e)
        determinant = a * a - b * b
        sigma = a + b if rank == 1 else abs(a - b)
        return {
            "schema_version": 2,
            "cutoff": "1",
            "tolerance": "1e-12",
            "precision_bits": 128,
            "rank": rank,
            "residual": ["1", "0.8", "1e-13"][rank],
            "residual_history": ["1", "0.8", "1e-13"][: rank + 1],
            "t_nodes": ["0", "1"][:rank],
            "omega_nodes": ["-1", "1"][:rank],
            "pivots": [mp.nstr(a, 45), mp.nstr(determinant / a, 45)][:rank],
            "core_det_history": [mp.nstr(a, 45), mp.nstr(determinant, 45)][:rank],
            "core_sigma_min": [mp.nstr(a, 45), mp.nstr(sigma, 45)][:rank],
            "metadata": {"configuration": {"grid_order": 4}},
        }


def test_independent_selected_cores_check_signed_determinant_and_svd() -> None:
    report = check_selected_cores(_record())
    assert report["status"] == "passed"
    assert [case["rank"] for case in report["checks"]] == [1, 2]
    with mp.workprec(192):
        for case in report["checks"]:
            assert mp.mpf(case["stored_determinant_relative_error"]) < mp.mpf("1e-40")
            assert mp.mpf(case["signed_pivot_product_relative_error"]) < mp.mpf("1e-40")
            assert mp.mpf(case["stored_sigma_relative_error"]) < mp.mpf("1e-40")
        assert mp.mpf(report["checks"][-1]["determinant"]) < 0


