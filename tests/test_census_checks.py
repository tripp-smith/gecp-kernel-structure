def test_batched_factorization_matches_independent_vector_solves() -> None:
    with mp.workprec(192):
        core = mp.matrix([[0, 2], [3, 4]])
        rhs = mp.matrix([[1, 2, 3], [4, 5, 6]])
        observed = _batched_lu_solve(core, rhs)
        for column in range(rhs.cols):
            reference = mp.lu_solve(core, rhs[:, column])
            assert max(
                abs(observed[i, column] - reference[i]) for i in range(2)
            ) < mp.mpf("1e-55")


def test_held_out_sample_is_every_panel_and_not_on_source_axes() -> None:
    times, frequencies, policy = panel_samples(1_000_000, 24)
    source_t, source_w = composite_chebyshev_grids(1_000_000, 24)
    assert not set(map(float, times)).intersection(source_t)
    assert not set(map(float, frequencies)).intersection(source_w)
    assert len(times) == 3 * policy["panel_counts"][0]
    assert len(frequencies) == 3 * policy["panel_counts"][1]
    assert all(count == 3 for axis in policy["samples_per_panel"] for count in axis)
    assert policy["sample_count"] == len(times) * len(frequencies)
    assert times == panel_samples(1_000_000, 24)[0]
    assert policy["coordinate_precision_bits"] == 53


def test_batched_solve_handles_noninvolutive_lu_permutation() -> None:
    with mp.workprec(192):
        core = mp.matrix([[0, 0, 2], [4, 0, 3], [1, 5, 6]])
        rhs = mp.matrix([[1, 2], [3, 4], [5, 6]])
        permutation, lower, upper = mp.lu(core)
        assert permutation != permutation.T
        assert mp.norm(permutation * core - lower * upper) == 0
        solution = _batched_lu_solve(core, rhs)
        assert mp.norm(core * solution - rhs) < mp.mpf("1e-55")
        for column in range(rhs.cols):
            expected = mp.lu_solve(core, rhs[:, column])
            assert mp.norm(solution[:, column] - expected) < mp.mpf("1e-55")


