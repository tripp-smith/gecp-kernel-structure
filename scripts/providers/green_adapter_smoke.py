"""Actual installed public Green reader/matrix-fit/archive acceptance."""

from __future__ import annotations

import argparse
import hashlib
import importlib
import json
import re
import subprocess
from pathlib import Path
from typing import Any

try:
    from .installed_wheel import installed_wheel_identity
except ImportError:
    from installed_wheel import installed_wheel_identity

PACKAGE_FILES = {
    "basis": "kernelgecp/basis.py",
    "green": "kernelgecp/integrations/green.py",
    "fitting": "kernelgecp/fitting.py",
}


def run_probe(
    native_root: Path,
    comparison_root: Path,
    expected_revision: str,
    output: Path,
    *,
    require_installed: bool,
) -> dict[str, Any]:
    root = Path(__file__).resolve().parents[2]
    result: dict[str, Any] = {
        "schema": "kernelgecp.green-adapter-smoke.v1",
        "status": "failed",
        "source_revision": expected_revision,
        "checks": {},
        "metrics": {},
        "execution_scope": "installed_wheel" if require_installed else "source_pilot",
    }
    stage = "source"
    try:
        revision = subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=root, text=True
        ).strip()
        if (
            revision != expected_revision
            or re.fullmatch("[0-9a-f]{40}", expected_revision) is None
        ):
            raise RuntimeError(
                "probe source revision differs from the requested frozen head"
            )
        modules = {
            name: importlib.import_module(
                "kernelgecp." + ("integrations.green" if name == "green" else name)
            )
            for name in PACKAGE_FILES
        }
        paths = {
            name: Path(module.__file__).resolve() for name, module in modules.items()
        }
        hashes = {}
        for name, relative in PACKAGE_FILES.items():
            actual = hashlib.sha256(paths[name].read_bytes()).hexdigest()
            expected = hashlib.sha256(
                subprocess.check_output(
                    ["git", "show", f"{revision}:{relative}"], cwd=root
                )
            ).hexdigest()
            if actual != expected or (
                require_installed and paths[name].is_relative_to(root)
            ):
                raise RuntimeError(
                    "imported module is not the exact installed source candidate"
                )
            hashes[relative] = actual
        result["module_sha256"] = hashes
        if require_installed:
            result["installation"] = installed_wheel_identity(paths, PACKAGE_FILES)
            result["checks"]["installed_distribution"] = True
        result["checks"]["source_identity"] = True
        stage = "actual_molecular_data"
        import numpy as np

        native_campaign = json.loads((native_root / "native-campaign.json").read_text())
        comparison = json.loads((comparison_root / "report.json").read_text())
        if (
            native_campaign.get("status") != "passed"
            or comparison.get("all_mandatory_passed") is not True
        ):
            raise RuntimeError(
                "actual native runs and the accepted comparison are required"
            )
        if comparison.get("source_revision") != expected_revision:
            raise RuntimeError(
                "comparison was generated by a different source candidate"
            )
        native_hash = hashlib.sha256(
            (native_root / "native-campaign.json").read_bytes()
        ).hexdigest()
        if native_hash != comparison.get("native_campaign_sha256"):
            raise RuntimeError("native campaign differs from the accepted comparison")
        cases = native_campaign.get("cases", [])
        if (
            len(cases) != 4
            or len(
                {(x["bond_length_angstrom"], x["native_grid_lambda"]) for x in cases}
            )
            != 4
        ):
            raise RuntimeError(
                "all four distinct native physical/grid cases are required"
            )
        maxima = {
            name: 0.0 for name in ("green_tau", "green_iw", "sigma_tau", "sigma_iw")
        }
        archives = {}
        for case in cases:
            name = case["directory"]
            folder = native_root / name
            data = modules["green"].read_green_tau(
                folder / "input.h5", folder / "sim.h5", folder / "bound-manifest.json"
            )
            if data.manifest_sha256 != case["manifest_sha256"]:
                raise RuntimeError("actual native manifest identity changed")
            if (
                not data.converged
                or data.sigma_static.shape != (1, 1, 2, 2)
                or data.units.energy != "hartree"
            ):
                raise RuntimeError(
                    "native matrix axes/static terms/units were not preserved"
                )
            training = np.unique(
                np.r_[np.arange(0, len(data.tau), 2), len(data.tau) - 1]
            )
            choices = [
                row
                for row in comparison["selection"]
                if row["case"] == name and row["method"] == "kernelgecp"
            ]
            if len(choices) != 1:
                raise RuntimeError("the frozen GECP selection is missing")
            choice = choices[0]
            for field, values, scale in (
                ("green", data.g_tau, 1),
                ("sigma", data.sigma_tau, 3),
            ):
                basis = modules["basis"].FermionicBasis(
                    data.beta, scale * choice["cutoff"], choice["eps"], grid_order=8
                )
                fit = basis.fit_tau(
                    values[training], data.tau[training], axis=0, rcond=1e-13
                )
                archive = output.parent / f"{name}-{field}-installed-fit.npz"
                fit.save(archive)
                restored = modules["basis"].FermionicFit.load(archive)
                with np.load(
                    comparison_root / name / "validation.npz", allow_pickle=False
                ) as reference:
                    for domain in ("tau", "iw"):
                        query = reference["tau" if domain == "tau" else "indices"]
                        evaluate = (
                            "evaluate_tau" if domain == "tau" else "evaluate_matsubara"
                        )
                        predicted = getattr(restored, evaluate)(query)
                        error = float(
                            np.max(abs(predicted - reference[field + "_" + domain]))
                        )
                        if (
                            predicted.shape != reference[field + "_" + domain].shape
                            or not np.isfinite(error)
                            or error > 1e-6
                        ):
                            raise RuntimeError(
                                "installed public matrix fit missed "
                                "the native holdout budget"
                            )
                        if not np.array_equal(getattr(fit, evaluate)(query), predicted):
                            raise RuntimeError(
                                "installed matrix archive did not preserve predictions"
                            )
                        maxima[field + "_" + domain] = max(
                            maxima[field + "_" + domain], error
                        )
                archives[archive.name] = hashlib.sha256(
                    archive.read_bytes()
                ).hexdigest()
        result["metrics"] = {
            "native_cases": 4,
            "matrix_archives": len(archives),
            "errors": maxima,
        }
        result["archive_sha256"] = archives
        result["checks"].update(
            actual_data=True,
            matrix_axes_units_static_terms=True,
            public_time_and_frequency_fits=True,
            matrix_archive_roundtrip=True,
        )
        result["status"] = "passed"
    except Exception as error:
        result["checks"][stage] = False
        result["failure"] = f"{type(error).__name__}: {error}"
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--native-root", type=Path, required=True)
    parser.add_argument("--comparison-root", type=Path, required=True)
    parser.add_argument("--source-revision", required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--require-installed", action="store_true")
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.unlink(missing_ok=True)
    result = run_probe(
        args.native_root,
        args.comparison_root,
        args.source_revision,
        args.output,
        require_installed=args.require_installed,
    )
    args.output.write_text(
        json.dumps(result, sort_keys=True, indent=2, allow_nan=False) + "\n"
    )
    print(json.dumps({"status": result["status"], "output": str(args.output)}))
    if result["status"] != "passed":
        raise SystemExit(1)


if __name__ == "__main__":
    main()
